/** Notification text is generated by the server; match complete templates only. */
export function notificationText(locale: Locale, text: string): string {
  if (locale === 'ru') return text;
  const patterns: [RegExp, string, string][] = [
    [/^По обращению ([A-Za-zА-Яа-я0-9-]+) запрошено уточнение\.$/, 'Clarification requested for request {n}.', '{n} өтініші бойынша нақтылау сұралды.'],
    [/^По обращению ([A-Za-zА-Яа-я0-9-]+) принято решение\.$/, 'A decision was made on request {n}.', '{n} өтініші бойынша шешім қабылданды.'],
    [/^Обращение ([A-Za-zА-Яа-я0-9-]+) поступило без ответственного\.$/, 'Request {n} arrived without an assignee.', '{n} өтініші жауапты адамсыз келіп түсті.'],
    [/^По обращению ([A-Za-zА-Яа-я0-9-]+) получено уточнение от автора\.$/, 'The author clarified request {n}.', '{n} өтініші бойынша автордан нақтылау алынды.'],
    [/^Срок рассмотрения обращения ([A-Za-zА-Яа-я0-9-]+) истекает менее чем через 24 часа\.$/, 'Request {n} is due in less than 24 hours.', '{n} өтінішін қарау мерзімі 24 сағаттан аз уақытта аяқталады.'],
  ];
  for (const [pattern, en, kk] of patterns) { const match = pattern.exec(text); if (match) return (locale === 'en' ? en : kk).replace('{n}', match[1]!); }
  return text;
}
/** Translate only the deterministic aggregate template, never free-form model text. */
export function digestTemplate(locale: Locale, text: string): string {
  if (locale === 'ru') return text;
  if (text === 'Обращений за период нет.') return translate(locale, text);
  let m = /^Всего за период: (\d+)\.$/.exec(text);
  if (m) return translate(locale, 'Всего за период: {count}.', { count: m[1]! });
  m = /^Просрочено: (\d+)\.$/.exec(text);
  if (m) return translate(locale, 'Просрочено: {count}.', { count: m[1]! });
  m = /^За период поступило обращений: (\d+)\. (?:Топ-категория — (.+?): (\d+)\. )?Просрочено обращений из этого периода: (\d+)\.$/.exec(text);
  if (m) return [translate(locale, 'За период поступило обращений: {count}.', { count: m[1]! }), m[2] ? translate(locale, 'Топ-категория — {name}: {count}.', { name: m[2], count: m[3]! }) : '', translate(locale, 'Просрочено обращений из этого периода: {count}.', { count: m[4]! })].filter(Boolean).join(' ');
  return text;
}
